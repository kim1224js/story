)

fun renderStoryForUser(rawStory: String, userId: String): String {
    var rendered = rawStory
    if (userId in storyFriendNames) {
        rendered = rendered.replace(userId, "${userId}친구")
    }
    rendered = rendered.replace("{PLAYER}", userId)
    return if ("{PLAYER}" in rawStory) rendered
    else "${userId}도 무릉도원 친구들과 함께 이 이야기의 한가운데 있었다.\n\n$rendered"
}

fun stageClearCost(chapter: Int): Long =
    storyChapters.getOrNull((chapter - 1).coerceIn(0, storyChapters.lastIndex))?.clearCost
        ?: storyChapters.last().clearCost

fun chapterRewardMultiplier(chapter: Int): Long =
    (stageClearCost(chapter) / 1_000_000L).coerceAtLeast(1L)
