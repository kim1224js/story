fun stageClearPercent(chapter: Int): Double =
    1.0 + (chapter.coerceIn(1, 50) - 1) * (19.0 / 49.0)

private fun balancedStageClearCost(chapter: Int): Long {
    val rawCost = MAX_PLAYER_MONEY * stageClearPercent(chapter) / 100.0
    return ((rawCost / 10_000.0).roundToLong() * 10_000L)
        .coerceIn(10_000L, MAX_PLAYER_MONEY)
}

val storyChapters =
    (
        storySeasonOneChapters + storySeasonTwoChapters + storySeasonThreeChapters +
            storySeasonFourChapters + storySeasonFiveChapters
    ).map { chapter -> chapter.copy(clearCost = balancedStageClearCost(chapter.number)) }

private val storyFriendNames = listOf(
