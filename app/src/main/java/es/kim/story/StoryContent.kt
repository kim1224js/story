fun renderStoryForUser(rawStory: String, userId: String): String {
    var rendered = rawStory
    if (userId in storyFriendNames) {
        rendered = rendered.replace(userId, "${userId}친구")
    }
    rendered = rendered.replace("{PLAYER}", userId)
    if ("{PLAYER}" in rawStory || userId.isBlank()) return rendered

    val playerIntroductions = listOf(
        "그날의 현장에는 ${userId}의 자리도 분명히 남아 있었다.",
        "사건이 시작되기 전부터 ${userId}도 친구들과 같은 테이블에 앉아 있었다.",
        "이번 계획에서 모두가 흩어지지 않도록 곁을 지킨 사람은 바로 $userId.",
        "아무도 눈치채지 못한 첫 번째 변화는 ${userId}의 시선에서 발견됐다.",
        "친구들이 소란을 피우는 동안 그 곁에는 다음 수를 준비하는 ${userId}도 있었다.",
        "그날의 기록을 다시 펼치면 가장 먼저 ${userId}의 이름이 보인다.",
        "이번에도 $userId 역시 구경꾼으로 남지 않고 친구들과 함께 움직였다.",
        "상황이 예상과 다르게 흐르자 모두의 시선이 자연스럽게 ${userId}에게 향했다.",
        "무릉도원의 빈자리를 채운 것은 뒤늦게 합류한 ${userId}의 한마디였다.",
        "이 사건에 오래 남은 작은 선택의 주인공은 바로 $userId.",
        "친구들은 중요한 순간마다 ${userId}의 판단을 한 번 더 확인했다.",
        "소동이 끝난 뒤에도 그날의 일은 ${userId}의 기억에 선명하게 남았다.",
    )
    val introduction = playerIntroductions[Math.floorMod(rawStory.hashCode(), playerIntroductions.size)]
    return "$introduction\n\n$rendered"
}

fun stageClearCost(chapter: Int): Long =
    storyChapters.getOrNull((chapter - 1).coerceIn(0, storyChapters.lastIndex))?.clearCost
        ?: storyChapters.last().clearCost

fun chapterRewardMultiplier(chapter: Int): Double =
    stageClearCost(chapter) / 1_000_000.0

fun scaledChapterReward(baseReward: Long, chapter: Int): Long =
    (baseReward.toDouble() * chapterRewardMultiplier(chapter))
        .coerceAtMost(Long.MAX_VALUE.toDouble())
        .roundToLong()

fun rewardMultiplierLabel(multiplier: Double): String =
    if (multiplier % 1.0 == 0.0) {
        NumberFormat.getNumberInstance(Locale.KOREA).format(multiplier.toLong())
    } else {
        String.format(Locale.KOREA, "%,.1f", multiplier)
    }
